// Gives the unpacked extension a fixed ID: stores a public key in the manifest `key` field
// and writes the derived ID to src/shared/extension-id.ts. The private key is not needed.
import { createHash, generateKeyPairSync } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const MANIFEST = "src/extension/manifest.json";
const ID_FILE = "src/shared/extension-id.ts";

/** Chrome extension ID: first 32 hex chars of SHA-256(DER SPKI), with 0-f mapped to a-p. */
export function idFromPublicKeyDer(der) {
  const hex = createHash("sha256").update(der).digest("hex").slice(0, 32);
  return [...hex].map((c) => String.fromCharCode(97 + parseInt(c, 16))).join("");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const manifest = JSON.parse(readFileSync(MANIFEST, "utf8"));
  if (!manifest.key) {
    const { publicKey } = generateKeyPairSync("rsa", { modulusLength: 2048 });
    manifest.key = publicKey.export({ type: "spki", format: "der" }).toString("base64");
    writeFileSync(MANIFEST, JSON.stringify(manifest, null, 2) + "\n");
  }
  const id = idFromPublicKeyDer(Buffer.from(manifest.key, "base64"));
  writeFileSync(
    ID_FILE,
    `// Generated by scripts/gen-key.mjs. Do not edit.\nexport const EXTENSION_ID = "${id}";\n`,
  );
  console.log(id);
}
